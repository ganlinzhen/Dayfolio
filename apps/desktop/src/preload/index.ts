const invoke = (channel: string) => async (payload?: unknown) => {
  const result = await ipcRenderer.invoke(channel, payload);
  if (result?.ok && WRITE_CHANNEL.test(channel)) window.dispatchEvent(new Event('dayfolio:changed'));
  return result;
};

